    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
                                       
    if (jTextField1.getText().trim().isEmpty()
            || jTextField2.getText().trim().isEmpty()
            || jTextField3.getText().trim().isEmpty()
            || jTextField4.getText().trim().isEmpty()){

    javax.swing.JOptionPane.showMessageDialog(
    this,
    "Complete todos los campos."
        );
    return;
    }

    String nombre = jTextField1.getText();
    String dni = jTextField2.getText().trim();

if (!dni.matches("\\d{8}")) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "DNI incorrecto. Ingrese exactamente 8 dígitos."
    );
    jTextField2.requestFocus();
    return;
}

int edad;

try {
    edad = Integer.parseInt(jTextField3.getText());
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "La edad debe ser un número :)."
    );
    return;
}
    String telefono = jTextField4.getText();
    String sexo = cbnsexo.getSelectedItem().toString();

    Paciente paciente = new Paciente(
            nombre,
            dni,
            edad,
            telefono,
            sexo
    );

    boolean registrado = gestor.registrarPaciente(paciente);
    

    if (registrado) {
    ultimoPaciente = paciente;

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Paciente registrado correctamente."
    );

        jTextField1.setText("");
        jTextField2.setText("");
        jTextField3.setText("");
        jTextField4.setText("");
        

    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "ERROR: El paciente ya está registrado."
        );
    
    }
    }//GEN-LAST:event_jButton1ActionPerformed

