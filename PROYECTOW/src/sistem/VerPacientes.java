    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
 String dni = jTextField1.getText();

Paciente paciente = gestor.buscarPacientePorDni(dni);

if (paciente != null) {
    jTextField2.setText(paciente.getNombre());
    jTextField3.setText(String.valueOf(paciente.getEdad()));
    
Atencion atencionEncontrada = null;

for (Atencion a : RegistroAtencion.listaAtenciones) {
    if (a.getPaciente().getDni().equals(dni)) {
        atencionEncontrada = a;
        break; 
    }
}

if (atencionEncontrada != null) {
    jTextField4.setText(atencionEncontrada.getDiagnostico());

} else {
    jTextField4.setText("");
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "El paciente no tiene una atención registrada."
    );
}
if (paciente.aplicaCampanaInfantil()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "El paciente cumple con la Campaña contra Enfermedades para niños menores de 9 años.",
            "Campaña de Salud Infantil",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
        );
    } else {}
} else {
    jTextField2.setText("");
    jTextField3.setText("");
    jTextField4.setText("");

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Paciente no encontrado"
    );

}
    }//GEN-LAST:event_jButton1ActionPerformed

